// The CSS that the utility items add to a project, from their css and
// cssVars. write-utilities-css.ts writes it to utilities.css, which the docs
// site imports, so its previews use exactly what the CLI installs.
import registry from "../registry.json"

type CssTree = { [selector: string]: string | CssTree }

function block(selector: string, body: CssTree, depth: number): string {
  const indent = "  ".repeat(depth)
  const lines = Object.entries(body).map(([key, value]) =>
    typeof value === "string"
      ? `${indent}  ${key}: ${value};`
      : block(key, value, depth + 1)
  )
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`
}

function declarations(selector: string, vars: Record<string, string>) {
  return block(
    selector,
    Object.fromEntries(
      Object.entries(vars).map(([name, value]) => [`--${name}`, value])
    ),
    0
  )
}

// Every utility's CSS, or only the named items'. The docs site shows one
// item's for its manual installation.
export function utilitiesCss(names?: readonly string[]) {
  const parts: string[] = []
  for (const item of registry.items) {
    if (!item.categories?.includes("utility")) continue
    if (names && !names.includes(item.name)) continue
    const rules: string[] = []
    if ("cssVars" in item && item.cssVars) {
      const { theme, light, dark } = item.cssVars
      if (light) rules.push(declarations(":root", light))
      if (dark) rules.push(declarations(".dark", dark))
      if (theme) rules.push(declarations("@theme inline", theme))
    }
    if ("css" in item && item.css)
      for (const [selector, body] of Object.entries(
        item.css as unknown as CssTree
      ))
        rules.push(
          typeof body === "string"
            ? `${selector}: ${body};`
            : block(selector, body, 0)
        )
    if (rules.length)
      parts.push(
        names
          ? rules.join("\n\n")
          : `/* ${item.title} */\n${rules.join("\n\n")}`
      )
  }
  const css = parts.join("\n\n")
  return names
    ? css
    : `/* Generated by scripts/utilities-css.ts from registry.json. */\n\n${css}\n`
}
