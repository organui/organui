// Builds registry/base-nova/growth-chart/growth-standards.ts from the WHO
// Child Growth Standards (WHO Multicentre Growth Reference Study Group, 2006).
//
// WHO publishes the standards as LMS parameters by day of age, from birth to
// 1856 days, in its anthro package. This script samples them at each month,
// as WHO's own monthly tables do (one month is 30.4375 days), interpolating
// linearly between days. Recumbent length (under 24 months) and standing
// height (from 24 months) are separate curves in the standards, so each is
// sampled only from its own rows and month 24 appears in both.
//
// Run from packages/registry: bun scripts/prepare-growth-standards.ts
import { createHash } from "node:crypto"
import { writeFile } from "node:fs/promises"

const source = {
  repository: "https://github.com/WorldHealthOrganization/anthro",
  commit: "b776d8a12b1c97369c748b561159fd2ec4f4db58",
  files: {
    weight: {
      path: "data-raw/growthstandards/weianthro.txt",
      sha256:
        "bc15a6a623dd1d5beaeed1497666332aa54bc4ccd15ff9658c487d79694ab77b",
    },
    length: {
      path: "data-raw/growthstandards/lenanthro.txt",
      sha256:
        "709f7a11881451daf7820f022d363d5bdb93746b5361d6bd9218af6ff838e0c2",
    },
    head: {
      path: "data-raw/growthstandards/hcanthro.txt",
      sha256:
        "e794e46f06b91223ad2c6435148dc08794a1d75b67613a652c3151201a98bf7c",
    },
  },
}
const daysPerMonth = 30.4375
type Row = { sex: number; age: number; lms: [number, number, number] }

async function rows(file: { path: string; sha256: string }) {
  const url = `${source.repository.replace("github.com", "raw.githubusercontent.com")}/${source.commit}/${file.path}`
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  const text = await response.text()
  const hash = createHash("sha256").update(text).digest("hex")
  if (hash !== file.sha256) throw new Error(`${file.path}: sha256 ${hash}`)
  const [header, ...lines] = text.trim().split(/\r?\n/)
  const columns = header!.split("\t")
  return lines.map((line) => {
    const cells = line.split("\t")
    const value = (name: string) => cells[columns.indexOf(name)]!
    return {
      sex: Number(value("sex")),
      age: Number(value("age")),
      loh: columns.includes("loh") ? value("loh") : null,
      lms: [Number(value("l")), Number(value("m")), Number(value("s"))],
    } as Row & { loh: string | null }
  })
}

// Samples one sex's rows at the given months, extrapolating from the nearest
// two days at the ends of a segment (month 24 falls half a day past the last
// length row).
function monthly(segment: Row[], months: number[]) {
  const byAge = new Map(segment.map((row) => [row.age, row.lms]))
  const ages = segment.map(({ age }) => age)
  const first = Math.min(...ages)
  const last = Math.max(...ages)
  return months.map((month) => {
    const day = month * daysPerMonth
    const lower = Math.min(Math.max(Math.floor(day), first), last - 1)
    const a = byAge.get(lower)!
    const b = byAge.get(lower + 1)!
    const t = day - lower
    return a.map((value, index) => value + (b[index]! - value) * t)
  })
}

const range = (from: number, to: number) =>
  Array.from({ length: to - from + 1 }, (_, index) => from + index)
const sexes = { female: 2, male: 1 } as const
const tables: Record<string, Record<string, number[][]>> = {}
const weight = await rows(source.files.weight)
const length = await rows(source.files.length)
const head = await rows(source.files.head)
for (const [name, sex] of Object.entries(sexes)) {
  const of = (all: Row[]) => all.filter((row) => row.sex === sex)
  ;(tables.weight ??= {})[name] = monthly(of(weight), range(0, 60))
  ;(tables.length ??= {})[name] = monthly(
    of(length.filter(({ loh }) => loh === "L")),
    range(0, 24)
  )
  ;(tables.height ??= {})[name] = monthly(
    of(length.filter(({ loh }) => loh === "H")),
    range(24, 60)
  )
  ;(tables.head ??= {})[name] = monthly(of(head), range(0, 60))
}

const digits = [4, 4, 5]
let out = `// Generated by packages/registry/scripts/prepare-growth-standards.ts from the
// WHO Child Growth Standards (WHO Multicentre Growth Reference Study Group,
// 2006), as published in ${source.repository}
// at ${source.commit}.
// Do not edit by hand.
//
// Each table lists [L, M, S] parameters by completed month: length runs from
// 0 to 24 months, height from 24 to 60, and the others from 0 to 60.

export type GrowthTable = {
  /** Age in months of the first row. */
  start: number
  lms: readonly (readonly [number, number, number])[]
}

export const growthStandards = {
`
const starts: Record<string, number> = { height: 24 }
for (const [measure, bySex] of Object.entries(tables)) {
  out += `  ${measure}: {\n`
  for (const [sex, values] of Object.entries(bySex)) {
    out += `    ${sex}: {\n      start: ${starts[measure] ?? 0},\n      lms: [\n`
    for (const lms of values)
      out += `        [${lms.map((value, index) => Number(value.toFixed(digits[index]))).join(", ")}],\n`
    out += `      ],\n    },\n`
  }
  out += `  },\n`
}
out += `} satisfies Record<string, Record<"female" | "male", GrowthTable>>\n`
await writeFile(
  new URL(
    "../registry/base-nova/growth-chart/growth-standards.ts",
    import.meta.url
  ),
  out
)
